import {createHash} from 'node:crypto';
import {readFile,writeFile} from 'node:fs/promises';
import {MOTION_CATALOG} from '../lib/motion/catalog.ts';
import {MOTION_CACHE_POLICY} from '../lib/motion/cache-policy.ts';

// A changed image gets a new cache key without invalidating the rest of the pack.
const sources=new Set(MOTION_CATALOG.map(asset=>asset.src));
const manifest={};
for(const src of [...sources].sort()){
 const bytes=await readFile(new URL('../public'+src,import.meta.url));
 if(bytes.length>MOTION_CACHE_POLICY.maxAssetBytes)throw Error(`素材超过单文件 4 MiB 限制，请拆分图集：${src}`);
 if(bytes.toString('ascii',0,4)!=='RIFF'||bytes.toString('ascii',8,12)!=='WEBP')throw Error(`不是有效的 WebP 文件：${src}`);
 manifest[src]={revision:createHash('sha256').update(bytes).digest('hex').slice(0,20),bytes:bytes.length};
}
const output='// Generated by scripts/build-motion-cache.mjs. Do not edit by hand.\nexport const MOTION_ASSETS:Record<string,{revision:string;bytes:number}>='+JSON.stringify(manifest,null,1)+';\n';
const path=new URL('../lib/motion/asset-manifest.ts',import.meta.url);
if(await readFile(path,'utf8').catch(()=>'')!==output){
 if(process.argv.includes('--check'))throw Error('动画缓存清单已过期，请运行 npm run assets:build 并提交清单。');
 await writeFile(path,output);
}
const active=MOTION_CATALOG.filter(asset=>asset.active);
const total=active.reduce((sum,asset)=>sum+manifest[asset.src].bytes,0);
console.log(`动画素材：${sources.size} 个文件，当前包 ${(total/1024/1024).toFixed(1)} MiB；内容指纹已校验。`);
